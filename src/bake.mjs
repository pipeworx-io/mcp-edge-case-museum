#!/usr/bin/env node
/**
 * Bake the Edge Case Museum index (fleet #3034).
 *
 * Reads every exhibit in src/exhibits/<category>/<id>.json
 * and writes src/ecm-index-data.ts, which is registered in
 * workers/gateway/src/pack-baked-indexes.json: it ships to KV and the gateway
 * injects it as args._bakedIndex, so the pack never value-imports it.
 *
 * The bake is the second half of the "no unexecuted claim" rule. The harness
 * (src/harness.mjs) runs every python / javascript repro
 * and records sha256(code, expected_output) in src/verified.json. This script
 * REFUSES to write the module if any executable repro is missing from that file
 * or its hash differs, i.e. if anyone edited a repro or its output without
 * re-running it. Documented (non-executed) repros are shipped labelled as such.
 *
 * Usage:  node src/bake.mjs [--check]
 *         --check  validate and compare with the committed module; exit 1 if stale.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadExhibits, validateExhibit, reproHash, normalizeOutput, RUNNABLE } from './harness.mjs';

const PACK = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ROOT = PACK;
const DIR = path.join(PACK, 'src/exhibits');
const OUT = path.join(PACK, 'src/ecm-index-data.ts');
const CHECK = process.argv.includes('--check');

const loaded = loadExhibits(DIR);
const errors = [];
for (const e of loaded) errors.push(...validateExhibit(e));
const verified = existsSync(path.join(PACK, 'src/verified.json')) ? JSON.parse(readFileSync(path.join(PACK, 'src/verified.json'), 'utf8')).repros ?? {} : {};
const exhibits = [];
const ids = new Set();
for (const { ex, file } of loaded) {
  if (!ex) continue;
  if (ids.has(ex.id)) errors.push(`duplicate id ${ex.id}`);
  ids.add(ex.id);
  for (const r of ex.repros ?? []) {
    if (r.status === 'documented' || !RUNNABLE[r.language]) continue;
    const key = `${ex.id}:${r.language}`;
    const row = verified[key];
    if (typeof r.expected_output !== 'string') errors.push(`${path.relative(ROOT, file)}: ${r.language} repro has no expected_output; run the harness with --capture`);
    else if (!row) errors.push(`${key}: not in src/verified.json; run node src/harness.mjs`);
    else if (row.sha256 !== reproHash(r.code, normalizeOutput(r.expected_output))) errors.push(`${key}: code or expected_output changed since the harness last ran it; re-run the harness`);
  }
  exhibits.push(ex);
}
for (const ex of exhibits) for (const rel of ex.related ?? []) if (!ids.has(rel)) errors.push(`${ex.id}: related id "${rel}" does not exist`);
if (exhibits.length < 1) errors.push('no exhibits found');
if (errors.length) {
  console.error(`edge-case-museum bake REFUSED (${errors.length} problem(s)):\n  ${errors.slice(0, 60).join('\n  ')}`);
  process.exit(1);
}

exhibits.sort((a, b) => a.category.localeCompare(b.category) || a.id.localeCompare(b.id));
const shipped = exhibits.map((ex) => ({
  id: ex.id,
  title: ex.title,
  category: ex.category,
  assumption: ex.assumption,
  input: { display: ex.input.display, description: ex.input.description ?? '' },
  what_goes_wrong: ex.what_goes_wrong,
  why: ex.why,
  affects: ex.affects,
  repros: ex.repros.map((r) =>
    r.status === 'documented'
      ? { language: r.language, status: 'documented', note: r.note, source: r.source }
      : { language: r.language, status: 'verified', code: r.code, expected_output: normalizeOutput(r.expected_output), verified_with: verified[`${ex.id}:${r.language}`].verified_with },
  ),
  fix: ex.fix,
  related: ex.related ?? [],
  sources: ex.sources,
  tags: ex.tags,
  test_cases: ex.test_cases ?? [],
}));
const byCat = {};
for (const ex of shipped) byCat[ex.category] = (byCat[ex.category] ?? 0) + 1;
const runtimes = JSON.parse(readFileSync(path.join(PACK, 'src/verified.json'), 'utf8')).runtimes ?? {};
// data_as_of is the content's date, not the bake's: the newest exhibit file's last commit would be ideal,
// but a deterministic module matters more for --check, so it is passed in or taken from verified.json's runtimes stamp.
const DATA_AS_OF = process.env.ECM_DATA_AS_OF ?? (existsSync(OUT) ? (readFileSync(OUT, 'utf8').match(/DATA_AS_OF = "([^"]+)"/)?.[1] ?? new Date().toISOString().slice(0, 10)) : new Date().toISOString().slice(0, 10));

const body = `// GENERATED by src/bake.mjs from src/exhibits/ — do not hand-edit; re-run the script.
// ${shipped.length} exhibits (${Object.entries(byCat).map(([k, v]) => `${k} ${v}`).join(', ')}) · repros verified with ${Object.values(runtimes).join(' and ')}
// Registered in workers/gateway/src/pack-baked-indexes.json; the pack reads it as args._bakedIndex and never value-imports this module.

export interface Repro { language: string; status: 'verified' | 'documented'; code?: string; expected_output?: string; verified_with?: string; note?: string; source?: string }
export interface TestCase { inputs: unknown[]; relation: 'equal' | 'not_equal' | 'returns' | 'no_crash' | 'raises'; expected?: unknown; note?: string }
export interface Exhibit {
  id: string; title: string; category: string; assumption: string; input: { display: string; description: string };
  what_goes_wrong: string; why: string; affects: string[]; repros: Repro[]; fix: string; related: string[];
  sources: { title: string; url: string }[]; tags: string[]; test_cases: TestCase[];
}

export const DATA_AS_OF = ${JSON.stringify(DATA_AS_OF)};
export const RUNTIMES: Record<string, string> = ${JSON.stringify(runtimes)};
export const EXHIBITS: Exhibit[] = ${JSON.stringify(shipped)};
`;
if (CHECK) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (cur !== body) {
    console.error('edge-case-museum: src/ecm-index-data.ts is stale; run node src/bake.mjs');
    process.exit(1);
  }
  console.log(`edge-case-museum index up to date: ${shipped.length} exhibits`);
} else {
  writeFileSync(OUT, body);
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${shipped.length} exhibits (${Object.entries(byCat).map(([k, v]) => `${k} ${v}`).join(', ')}), ${(body.length / 1024).toFixed(0)} KB`);
}
